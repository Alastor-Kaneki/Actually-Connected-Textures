template <class T>
inline T& at(void* base, size_t offset) { return *reinterpret_cast<T*>(static_cast<char*>(base) + offset); }
template <class T>
inline const T& at(const void* base, size_t offset) {
    return *reinterpret_cast<const T*>(static_cast<const char*>(base) + offset);
}

inline const void* legacyOf(const void* block) { return block ? at<const void*>(block, off::Block_Legacy) : nullptr; }

inline const std::string* uvPath(const void* uv) { return &at<std::string>(uv, off::UV_Path); }

