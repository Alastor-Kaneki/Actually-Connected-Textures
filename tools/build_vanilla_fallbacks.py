#!/usr/bin/env python3
"""Build offline fallback PNGs from Mojang/bedrock-samples v1.26.60.5.

Usage: python3 tools/build_vanilla_fallbacks.py <bedrock-samples/resource_pack>
Generated archives stay out of git; CI builds and bundles them with the app.
Only terrain/flipbook images referenced by the converter's vanilla table are kept.
"""
import io
import json
from pathlib import Path
import sys
import zipfile

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def paths(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for item in value:
            yield from paths(item)
    elif isinstance(value, dict):
        if "variations" in value:
            yield from paths(value["variations"])
        elif "path" in value:
            yield value["path"]


def main():
    rp = Path(sys.argv[1])
    vanilla = json.loads((ROOT / "converter/data/vanilla_26.60.json").read_text())
    wanted = set()
    for value in vanilla["terrain_textures"].values():
        wanted.update(paths(value))
    wanted.update(e["flipbook_texture"] for e in vanilla["flipbooks"])
    data = io.BytesIO()
    count = 0
    with zipfile.ZipFile(data, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in sorted(wanted):
            source = next((rp / (path + ext) for ext in (".png", ".tga") if (rp / (path + ext)).is_file()), None)
            if source is None:
                continue  # some terrain entries are generated by the game; conversion fails clearly if needed
            image = Image.open(source).convert("RGBA")
            png = io.BytesIO()
            image.save(png, "PNG", optimize=True)
            entry = zipfile.ZipInfo(path + ".png", date_time=(2026, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(entry, png.getvalue())
            count += 1
    for directory in ("converter/data", "ctm-forge/core/src/main/resources"):
        target = ROOT / directory / "vanilla_fallbacks.zip"
        target.write_bytes(data.getvalue())
    print(f"Bundled {count} fallback images ({len(data.getvalue())} bytes) for Python and Kotlin")


if __name__ == "__main__":
    main()
